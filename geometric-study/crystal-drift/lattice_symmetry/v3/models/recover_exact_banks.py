"""Regenerate missing deterministic train-only banks and publish only exact original bytes."""
import argparse,hashlib,json,os,sys,time
from io import BytesIO
from pathlib import Path
if os.environ.get('CRYTALDRIFT_NUMBA_SITE'):sys.path.append(os.environ['CRYTALDRIFT_NUMBA_SITE'])
import numpy as np
from .prepare import CACHE,BLOCK,make_shard
from .sampler import HERE,Sampler

def main():
    ap=argparse.ArgumentParser();ap.add_argument('root',type=Path);ap.add_argument('--part',type=int,default=0);ap.add_argument('--workers',type=int,default=1)
    ap.add_argument('--reverse',action='store_true')
    a=ap.parse_args();start=time.monotonic();s=Sampler()
    inventory=json.loads((HERE/'fresh-bank-sha256.json').read_text())['shards']
    first=True;new=0
    for epoch in (range(7,0,-1) if a.reverse else range(1,8)):
        order=np.random.default_rng(55171+epoch).permutation(len(s.ids))
        positions=list(enumerate(range(0,len(order),BLOCK)))
        for k,lo in (reversed(positions) if a.reverse else positions):
            name=f'epoch-{epoch:02}/train-{k:03}.npz'
            key=inventory[name];p=a.root/'banks'/name
            if (CACHE/name).exists() or p.is_file() or k%a.workers!=a.part:continue
            values=make_shard(s,order[lo:lo+BLOCK],k,epoch,in_memory=True)
            f=BytesIO();np.savez_compressed(f,**values);buf=f.getvalue()
            if hashlib.sha256(buf).hexdigest()!=key:raise ValueError('Regenerated bytes differ at '+name)
            p.parent.mkdir(parents=True,exist_ok=True);temp=p.with_name(p.name+f'.generated-{os.getpid()}')
            with temp.open('xb') as h:h.write(buf)
            try:os.link(temp,p)
            except FileExistsError:
                if hashlib.sha256(p.read_bytes()).hexdigest()!=key:raise ValueError('Different published bank')
            temp.unlink()
            new+=1
            if first or new%50==0:print('Rebuilt exact bank',name,new,round(time.monotonic()-start,1),flush=True)
            first=False
    print('Completed byte-for-byte generation',new,round(time.monotonic()-start,1),flush=True)
if __name__=='__main__':main()
